#!/usr/bin/env python3
"""Generate supabase/snippets/insert_reference_subfloor_systems.sql from reference_subfloor_data.py.

    python3 scripts/reference/generate_reference_subfloor_sql.py

The SQL is for the DATA STUDIO project only (never the RFQ/production project). It is idempotent:
re-running skips systems that already exist for the reference manufacturer.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from reference_subfloor_data import MANUFACTURER, CARDS, SOURCES, STANDARDS_NOTE

BAL_NOTE = (
    "Bushfire (BAL) overlay — AS 3959:2018 sets what the subfloor can be made from (secondary sources; confirm in the standard) [S]. "
    "BAL-12.5/19: unenclosed subfloor with members under 400 mm above ground needs bushfire-resisting timber or non-combustible members, or shielding/enclosure. "
    "BAL-29: unenclosed subfloor must meet BAL-29 clauses; verandah posts must be non-combustible or hardwood. "
    "BAL-40: post/column/stump clause not retrieved. Bushfire-resisting timbers are 750 kg/m3 or denser (Table E1). Add a BAL question to the order."
)

def q(s):
    return "NULL" if s is None or s == "" else "'" + str(s).replace("'", "''") + "'"

out = []
w = out.append
w("-- GENERATED by scripts/reference/generate_reference_subfloor_sql.py — edit reference_subfloor_data.py, then regenerate.")
w("-- BuildQuote Reference Systems: generic, manufacturer-neutral DECK SUBFLOOR cards (RFQ templates).")
w("-- Source of truth: Decks WA docs/system-card-drafts.md. ALL sizes/grades/quantities are placeholders until a")
w("-- builder AND an engineer review them. Rows are inserted as pending_review — NOTHING here is verified.")
w("-- Run manually against the DATA STUDIO project (ovndokzwkxpfjfobewaq). Do NOT run on the RFQ/production project.")
w("-- Idempotent: re-running skips systems that already exist for this manufacturer.")
w("-- Optional: apply migration 069_deck_type.sql first so deck_type is set to 'subfloor' (this script sets it only if the column exists).")
w("")
w("CREATE OR REPLACE FUNCTION pg_temp.ref_comp(p_mfr uuid, p_name text, p_cat text, p_uom text)")
w("RETURNS uuid LANGUAGE plpgsql AS $f$")
w("DECLARE v_id uuid;")
w("BEGIN")
w("  SELECT id INTO v_id FROM staged_components WHERE manufacturer_id = p_mfr AND name = p_name AND category IS NOT DISTINCT FROM p_cat LIMIT 1;")
w("  IF v_id IS NULL THEN")
w("    INSERT INTO staged_components (manufacturer_id, name, category, uom) VALUES (p_mfr, p_name, p_cat, p_uom) RETURNING id INTO v_id;")
w("  END IF;")
w("  RETURN v_id;")
w("END $f$;")
w("")
w("DO $$")
w("DECLARE")
w("  v_mfr uuid;")
w("  v_sys uuid;")
w("  v_doc uuid;")
w("BEGIN")
w(f"  SELECT id INTO v_mfr FROM data_studio_manufacturers WHERE slug = {q(MANUFACTURER['slug'])};")
w("  IF v_mfr IS NULL THEN")
w(f"    INSERT INTO data_studio_manufacturers (name, slug, description) VALUES ({q(MANUFACTURER['name'])}, {q(MANUFACTURER['slug'])}, {q(MANUFACTURER['description'])}) RETURNING id INTO v_mfr;")
w("  END IF;")
w("")
# source documents (one per link used)
used = []
for c in CARDS:
    for k in c["sources"]:
        if k not in used: used.append(k)
w("  -- Reference sources: links only (content is read at the source, not copied).")
for k in used:
    title, url, _role = SOURCES[k]
    w(f"  IF NOT EXISTS (SELECT 1 FROM source_documents WHERE manufacturer_id = v_mfr AND source_url = {q(url)}) THEN")
    w(f"    INSERT INTO source_documents (manufacturer_id, original_filename, document_name, document_type, source_url, ingest_kind, notes)")
    w(f"    VALUES (v_mfr, {q(url)}, {q(title)}, 'reference', {q(url)}, 'url_fetch', 'Reference source for generic subfloor cards — read at source.');")
    w("  END IF;")
w("")
for c in CARDS:
    primary = SOURCES[c["sources"][0]][1]
    notes = " ".join(filter(None, [
        f"Code {c['code']}. {c['description'].split('. ')[-1] if False else ''}".strip(),
        "VARIABLES TO CONFIRM: " + c["variables"],
        ("OPEN QUESTIONS: " + c["questions"]) if c.get("questions") else "",
        STANDARDS_NOTE,
        BAL_NOTE if c["code"] not in ("DWA-SITE",) else "",
        "STATUS: placeholder lists for builder + engineer review; not advice.",
    ]))
    attrs = [{"label": l, "value": v} for (l, v) in c["attrs"]]
    w(f"  -- ===== {c['code']} — {c['name']} =====")
    w(f"  IF NOT EXISTS (SELECT 1 FROM staged_systems WHERE manufacturer_id = v_mfr AND product_code = {q(c['code'])}) THEN")
    w(f"    SELECT id INTO v_doc FROM source_documents WHERE manufacturer_id = v_mfr AND source_url = {q(primary)} LIMIT 1;")
    w("    INSERT INTO staged_systems (manufacturer_id, source_document_id, name, product_code, category, subcategory, description, notes, custom_technical_attributes)")
    w(f"    VALUES (v_mfr, v_doc, {q(c['name'])}, {q(c['code'])}, 'Subfloor', {q(c['subcategory'])}, {q(c['description'])}, {q(notes)}, {q(json.dumps(attrs))}::jsonb)")
    w("    RETURNING id INTO v_sys;")
    if c["profiles"]:
        w("    INSERT INTO staged_system_profiles (staged_system_id, name, profile_name, dimensions, uom, sort_order) VALUES")
        rows = [f"      (v_sys, {q(n)}, {q(pn)}, {q(d)}, {q(u)}, {i})" for i, (n, pn, d, u) in enumerate(c["profiles"], 1)]
        w(",\n".join(rows) + ";")
    for i, (grp, name, uom, role, note) in enumerate(c["components"], 1):
        w(f"    INSERT INTO staged_system_components (staged_system_id, staged_component_id, role, notes, sort_order)")
        w(f"    VALUES (v_sys, pg_temp.ref_comp(v_mfr, {q(name)}, {q(grp)}, {q(uom)}), {q(role)}, {q(note)}, {i});")
    for j, k in enumerate(c["sources"]):
        title, url, role = SOURCES[k]
        w(f"    INSERT INTO system_sources (manufacturer_id, staged_system_id, role, label, url, sort_order) VALUES (v_mfr, v_sys, {q(role)}, {q(title)}, {q(url)}, {j}) ON CONFLICT DO NOTHING;")
    w("  END IF;")
    w("")
w("END $$;")
w("")
w("-- Mark them as subfloor products if migration 069 (deck_type) has been applied.")
w("DO $$")
w("BEGIN")
w("  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'staged_systems' AND column_name = 'deck_type') THEN")
w(f"    EXECUTE 'UPDATE staged_systems SET deck_type = ''subfloor'' WHERE deck_type IS NULL AND manufacturer_id = (SELECT id FROM data_studio_manufacturers WHERE slug = ''{MANUFACTURER['slug']}'')';")
w("  END IF;")
w("END $$;")
w("")
w("-- Check: select s.product_code, s.name, count(sc.id) as components from staged_systems s")
w("--   join data_studio_manufacturers m on m.id = s.manufacturer_id left join staged_system_components sc on sc.staged_system_id = s.id")
w(f"--   where m.slug = '{MANUFACTURER['slug']}' group by 1,2 order by 1;")
path = os.path.join(os.path.dirname(__file__), "..", "..", "supabase", "snippets", "insert_reference_subfloor_systems.sql")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), len(out), "lines;", sum(len(c['components']) for c in CARDS), "component links;", len(CARDS), "systems")
